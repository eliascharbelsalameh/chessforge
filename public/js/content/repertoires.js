export function allLines() {
  const out = [];
  for (const rep of REPERTOIRES) {
    for (const line of rep.lines) out.push({ rep, line });
  }
  return out;
}

export function findLine(lineId) {
  for (const rep of REPERTOIRES) {
    const line = rep.lines.find((l) => l.id === lineId);
    if (line) return { rep, line };
  }
  return null;
}
